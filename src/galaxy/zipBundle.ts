import JSZip from 'jszip';
import { exportGalaxyToGLB } from './gltfExport';
import { capturePosterImage } from './posterExport';
import { generateOpenSeaMetadata } from './metadataExport';
import { GalaxyParams } from '../types/galaxy';
import * as THREE from 'three';

export interface BundleProgressCallback {
  (step: string, percentage: number): void;
}

export async function createFullNftAssetZipBundle(
  exportableGroup: THREE.Group,
  renderer: THREE.WebGLRenderer,
  scene: THREE.Scene,
  camera: THREE.Camera,
  params: GalaxyParams,
  onProgress?: BundleProgressCallback
): Promise<Blob> {
  const zip = new JSZip();

  onProgress?.('Generating 3D Binary Model (.glb)...', 20);
  const glbBlob = await exportGalaxyToGLB(exportableGroup);
  zip.file('sombrero-galaxy-m104.glb', glbBlob);

  onProgress?.('Capturing Ultra-Res 2K Poster (.png)...', 50);
  const poster = await capturePosterImage(renderer, scene, camera, 2048);
  zip.file('sombrero-galaxy-poster-2048.png', poster.blob);

  onProgress?.('Generating OpenSea JSON Metadata...', 75);
  const metadata = generateOpenSeaMetadata(params, {
    tokenId: 104,
    title: `Sombrero Galaxy (M104) Live 3D NFT #${Math.floor(Math.random() * 900 + 100)}`,
  });
  zip.file('metadata.json', JSON.stringify(metadata, null, 2));

  // OpenSea Mint & Pinning Guide Markdown
  const guideMarkdown = `# OpenSea 3D NFT Mint & Pinning Guide
## Sombrero Galaxy (Messier 104 / NGC 4594)

Congratulations on generating your 3D Sombrero Galaxy Live NFT Asset Bundle!
This package contains everything needed to launch or add this 3D masterpiece to your OpenSea gallery collection.

---

### Package Contents:
1. **\`sombrero-galaxy-m104.glb\`**:
   - The primary 3D interactive asset.
   - Formatted in binary GLTF 2.0 with embedded PBR materials and procedural particle systems.
   - Fully compatible with OpenSea's \`<model-viewer>\` interactive preview, Blender, Apple AR QuickLook, and Unreal Engine.
2. **\`sombrero-galaxy-poster-2048.png\`**:
   - 2048x2048 high-resolution rendered cover image.
   - Used as the initial placeholder and thumbnail on OpenSea before the 3D model loads.
3. **\`metadata.json\`**:
   - ERC-721 / ERC-1155 compliant metadata file conforming to OpenSea metadata standards.
   - Contains 14 detailed astrophysical traits, rarity rankings, and links.

---

### Step-by-Step Minting Instructions:

#### Option A: Direct OpenSea Studio (No-Code Drop)
1. Go to **OpenSea Studio** (https://opensea.io/studio).
2. Choose **Create an NFT** or create a new ERC-721 Collection.
3. In the media upload field:
   - Upload **\`sombrero-galaxy-m104.glb\`** as the primary interactive 3D media.
   - Upload **\`sombrero-galaxy-poster-2048.png\`** as the preview thumbnail.
4. Fill in the Title: \`Sombrero Galaxy (Messier 104) Live 3D\`
5. Copy the trait properties from \`metadata.json\` into the OpenSea Traits section.
6. Click **Create / Mint** to publish directly to Ethereum, Polygon, Base, or Arbitrum!

#### Option B: Decentralized IPFS + Smart Contract (Manifold / Thirdweb / Custom)
1. Upload both \`sombrero-galaxy-m104.glb\` and \`sombrero-galaxy-poster-2048.png\` to IPFS using **Pinata** or **NFT.Storage**.
2. Note the IPFS hashes (CIDs):
   - Example Image CID: \`ipfs://Qm.../sombrero-galaxy-poster-2048.png\`
   - Example 3D Model CID: \`ipfs://Qm.../sombrero-galaxy-m104.glb\`
3. In \`metadata.json\`:
   - Replace the \`image\` field with your Image IPFS CID.
   - Replace the \`animation_url\` field with your 3D Model IPFS CID.
4. Upload \`metadata.json\` to IPFS.
5. In your smart contract \`tokenURI(tokenId)\`, return the IPFS URL of your \`metadata.json\`.
6. Refresh metadata on OpenSea, and your 3D Sombrero Galaxy will render live and fully interactive!

---

*Generated by Sombrero Galaxy 3D Live NFT Studio*
`;
  zip.file('OPENSEA_MINT_GUIDE.md', guideMarkdown);

  onProgress?.('Compressing Full Asset Bundle...', 90);
  const zipBlob = await zip.generateAsync({ type: 'blob' });
  onProgress?.('Complete!', 100);

  return zipBlob;
}
